-- ============================================================
-- SEFE · Cuadre de repartidores (cierre del día)
-- ============================================================
-- Cada día, logística cuadra con cada repartidor lo que tiene que
-- entregar: efectivo, cheques, boletas, contraseñas, facturas firmadas,
-- lo que regresa sin entregar y lo recogido en recolectas.
-- Cada cosa se marca "Recibido" en su propio registro (cobros_ruta,
-- documentos.entrega_info, paradas_ruta.hecha_info). Esta tabla guarda
-- el CIERRE del cuadre: quién lo recibió, cuándo, el efectivo contado,
-- la diferencia y una foto (resumen) de lo que se cuadró.
-- Un cuadre por repartidor y por día.
-- Seguro de correr de más: 'if not exists' / 'drop policy if exists'.
-- ============================================================

create table if not exists public.cuadres_ruta (
  id               bigint generated by default as identity primary key,
  piloto_id        bigint,
  piloto_nombre    text,
  fecha            date not null,
  resumen          jsonb,            -- lo que se cuadró (items y montos)
  efectivo_esperado numeric(12,2),
  efectivo_contado  numeric(12,2),
  diferencia       numeric(12,2),
  nota             text,
  cerrado_por      text,
  cerrado_el       timestamptz not null default now(),
  unique (piloto_id, fecha)
);

alter table public.cuadres_ruta enable row level security;

drop policy if exists sefe_leer   on public.cuadres_ruta;
create policy sefe_leer   on public.cuadres_ruta for select to authenticated
  using ((select public.sefe_activo()));

drop policy if exists sefe_crear  on public.cuadres_ruta;
create policy sefe_crear  on public.cuadres_ruta for insert to authenticated
  with check ((select public.sefe_puede_escribir()));

drop policy if exists sefe_editar on public.cuadres_ruta;
create policy sefe_editar on public.cuadres_ruta for update to authenticated
  using ((select public.sefe_puede_escribir()))
  with check ((select public.sefe_puede_escribir()));

drop policy if exists sefe_borrar on public.cuadres_ruta;
create policy sefe_borrar on public.cuadres_ruta for delete to authenticated
  using ((select public.sefe_es_admin()));

grant select, insert, update, delete on public.cuadres_ruta to authenticated;
