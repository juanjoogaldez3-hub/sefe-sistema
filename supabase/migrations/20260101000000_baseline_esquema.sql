-- ============================================================
-- BASELINE — el esquema completo de SEFE, creado desde cero.
-- ============================================================
-- Esta es la PRIMERA migración: crea todas las tablas, llaves,
-- relaciones e índices de una base vacía. Va antes que
-- base_historico y que todas las demás.
--
-- ── PARA QUÉ SIRVE ──────────────────────────────────────────
-- Para dar de alta un CLIENTE NUEVO: se crea un proyecto Supabase
-- vacío y, al correr las migraciones, esto arma toda la estructura.
-- Después, base_historico y las demás migraciones agregan lo que
-- vino evolucionando — pero como todas usan "if not exists", en una
-- base recién creada por este baseline simplemente no repiten nada.
--
-- ── EN PRODUCCIÓN Y PRUEBAS (bases que YA existen) ──────────
-- Es un NO-OP total. Todo está con "create table if not exists" /
-- "create index if not exists", así que no toca ni una tabla ni un
-- dato: sólo queda registrada como aplicada. La estructura de esas
-- bases ya está desde hace meses.
--
-- ── NOTAS ───────────────────────────────────────────────────
-- · Los id son IDENTITY (los genera Postgres), tal como en la base
--   real: 'always' donde el cliente nunca los manda, 'by default'
--   donde a veces sí.
-- · Las tablas de respaldo (_bkp_*) NO van: son de una limpieza
--   puntual, no parte del sistema.
-- · Las políticas RLS y el tiempo real los agregan sus propias
--   migraciones (rls / realtime), que corren después de ésta.
-- ============================================================


-- ── Catálogos base (sin dependencias) ───────────────────────
create table if not exists public.vendedores (
  id      bigint generated always as identity primary key,
  nombre  text not null,
  activo  boolean default true,
  creado  timestamptz default now()
);

create table if not exists public.pilotos (
  id      bigint generated always as identity primary key,
  nombre  text not null,
  activo  boolean default true,
  creado  timestamptz default now()
);

create table if not exists public.proveedores (
  id           bigint generated always as identity primary key,
  nombre       text not null,
  razon_social text,
  nit          text,
  telefono     text,
  correo       text,
  dias_credito integer default 0,
  activo       boolean default true,
  creado       timestamptz default now()
);

create table if not exists public.cuentas_banco (
  id            bigint generated by default as identity primary key,
  nombre        text not null,
  banco         text,
  numero        text,
  tipo          text default 'monetaria'::text,
  moneda        text default 'GTQ'::text,
  saldo_inicial numeric default 0,
  activo        boolean default true,
  creada        timestamptz default now()
);

create table if not exists public.categorias (
  nombre       text not null primary key,
  umbral_stock numeric not null default 10
);

create table if not exists public.productos (
  id                bigint generated always as identity primary key,
  codigo            text not null,
  nombre            text not null,
  precio            numeric(12,2) default 0,
  costo             numeric(12,2) default 0,
  unidad            text default 'UNI'::text,
  stock             numeric(12,2) default 0,
  proveedor_ids     jsonb default '[]'::jsonb,
  sku_proveedor     text,
  nombre_proveedor  text,
  activo            boolean default true,
  creado            timestamptz default now(),
  tipo_empaque      text default 'unidad'::text,
  unidades_por_caja integer,
  stock_cajas       numeric(12,2) default 0,
  marca             text,
  precio_caja       numeric default 0,
  precio_unidad     numeric default 0,
  conversiones      jsonb default '[]'::jsonb,
  categoria         text
);

create table if not exists public.talonarios (
  id             bigint generated always as identity primary key,
  numero_inicial integer not null,
  numero_final   integer not null,
  cantidad       integer not null default 50,
  asignado_a     text,
  asignado_id    bigint,
  descripcion    text,
  estado         text default 'activo'::text,
  fecha_entrega  date default CURRENT_DATE,
  creado         timestamptz default now()
);


-- ── Clientes (se referencia a sí mismo por las sedes) ───────
create table if not exists public.clientes (
  id                  bigint generated always as identity primary key,
  nit                 text not null default 'CF'::text,
  nombre              text not null,
  razon_social        text,
  direccion           text,
  email               text,
  tiempo_credito      integer default 0,
  vendedor_id         bigint references public.vendedores(id) on delete set null,
  sedes_de            bigint references public.clientes(id) on delete set null,
  contacto_pagos      jsonb default '{}'::jsonb,
  contacto_compras    jsonb default '{}'::jsonb,
  precios             jsonb default '{}'::jsonb,
  activo              boolean default true,
  creado              timestamptz default now(),
  direccion_entrega   text,
  fecha_alta          date,
  nits_secundarios    jsonb default '[]'::jsonb,
  cobro_info          jsonb default '{}'::jsonb,
  seguimientos        jsonb default '[]'::jsonb,
  sub_vendedor_nombre text,
  ruta                text
);


-- ── Documentos y su cobranza ────────────────────────────────
