create table if not exists public.recibos_anulados (
  id           bigint generated always as identity primary key,
  numero       integer not null,
  talonario_id bigint references public.talonarios(id) on delete set null,
  motivo       text,
  anulado_por  text,
  fecha        timestamptz default now()
);


-- ── Roles y usuarios ────────────────────────────────────────
create table if not exists public.roles (
  rol               text not null primary key,
  label             text not null,
  views             jsonb not null default '[]'::jsonb,
  anular            boolean default false,
  facturar          boolean default false,
  crear_cliente     boolean default false,
  editar_inventario boolean default false,
  registrar_abono   boolean default false,
  readonly          boolean default false,
  compra_especial   boolean default false,
  asignar_piloto    boolean default false,
  convertir_cajas   boolean default false
);

create table if not exists public.usuarios (
  id             bigint generated always as identity primary key,
  auth_id        uuid references auth.users(id) on delete set null,
  nombre         text not null,
  correo         text unique,
  rol            text not null default 'ventas'::text,
  activo         boolean default true,
  vendedor_id    bigint references public.vendedores(id) on delete set null,
  piloto_id      bigint references public.pilotos(id) on delete set null,
  creado         timestamptz default now(),
  recibe_resumen boolean default false
);


-- ── Auditoría (bitácora encadenada) ─────────────────────────
