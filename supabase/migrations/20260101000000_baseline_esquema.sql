  id                bigint generated always as identity primary key,
  documento_id      bigint references public.documentos(id) on delete cascade,
  doc_num           text,
  cliente           text,
  monto             numeric(12,2) not null,
  modo              text,
  no_boleta         text,
  no_recibo         text,
  cheque            text,
  banco             text,
  piloto            text,
  fecha             timestamptz default now(),
  estado            text default 'cobrado'::text,
  depositado_fecha  timestamptz,
  recibido_por      text,
  recibido_fecha    timestamptz,
  procesado_por     text,
  procesado_fecha   timestamptz
);


-- ── Compras y pagos a proveedores ───────────────────────────
create table if not exists public.compras (
  id               bigint generated always as identity primary key,
