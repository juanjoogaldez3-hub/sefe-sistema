  accion    text,
  detalle   text,
  prev_hash text,
  hash      text
);


-- ── Índices (los de rendimiento y el único de recibos) ──────
create index if not exists idx_abonos_documento        on public.abonos            (documento_id);
create index if not exists idx_clientes_nit            on public.clientes          (nit);
create index if not exists idx_clientes_vendedor       on public.clientes          (vendedor_id);
create index if not exists idx_cobros_ruta_estado      on public.cobros_ruta       (estado);
create index if not exists idx_compras_proveedor       on public.compras           (proveedor_id);
create index if not exists creditos_cliente_cliente_idx on public.creditos_cliente (cliente_id);
create index if not exists idx_documentos_cliente      on public.documentos        (cliente_id);
create index if not exists idx_documentos_estado       on public.documentos        (estado);
create index if not exists idx_documentos_piloto       on public.documentos        (piloto_id);
create index if not exists idx_documentos_tipo         on public.documentos        (tipo_doc);
create index if not exists idx_mov_cuenta              on public.movimientos_banco (cuenta_id);
create index if not exists idx_mov_fecha               on public.movimientos_banco (fecha);
create index if not exists idx_pagos_compra            on public.pagos_proveedor   (compra_id);
create unique index if not exists idx_recibos_anulados_numero on public.recibos_anulados (numero);
create index if not exists idx_talonarios_rango        on public.talonarios        (numero_inicial, numero_final);
