  metodo           text,
  referencia       text,
  no_recibo        text,
  comprobante      text,
  registrado_por   text,
  registrado_el    timestamptz default now(),
  anulado          boolean default false,
  motivo_anulacion text,
  es_cierre        boolean default false,
  creado           timestamptz default now(),
  cuenta_banco_id  bigint references public.cuentas_banco(id)
);


-- ── Cotizaciones y créditos del cliente ─────────────────────
