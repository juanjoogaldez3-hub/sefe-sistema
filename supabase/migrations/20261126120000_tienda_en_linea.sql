-- ============================================================
-- SEFE · Tienda en línea (fase 1: catálogo + carrito + pedido web)
-- ============================================================
-- La tienda (sistema.se-fe.com/tienda/) es PÚBLICA: la ve gente sin
-- usuario del sistema. Por eso NO lee las tablas directo (la RLS las
-- tiene cerradas para quien no es usuario activo): todo pasa por
-- funciones `tienda_*` que devuelven sólo lo que se puede mostrar
-- (nunca costos, proveedores ni existencias exactas) y que calculan
-- los precios EN LA BASE (el navegador del comprador no decide precios).
--
-- Tienda unificada: SEFE y LAML tienen productos con el mismo código.
-- La tienda muestra UNA ficha por código. El pedido web entra SIN
-- empresa a `pedidos_web`; adentro del sistema alguien decide qué
-- empresa lo vende y ahí se convierte en un pedido normal (PED-…).
--
-- Precio que ve el comprador:
--   · público: el precio de lista (si el código está en las dos
--     empresas con precio distinto, el más alto);
--   · cliente con acceso: su precio especial si lo tiene, si no el
--     precio de lista de SU empresa, y si no el de la otra.
--
-- La tienda nace APAGADA (ajustes.tienda.activa = false). Se enciende
-- desde el sistema: Tienda en línea → Configuración.
--
-- Seguro de correr de más: 'if not exists' / 'create or replace' /
-- 'drop policy if exists' / 'on conflict do nothing'.
-- ============================================================

