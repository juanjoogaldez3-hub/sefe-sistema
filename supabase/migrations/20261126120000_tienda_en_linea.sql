  creado           timestamptz not null default now(),
  estado           text not null default 'nuevo',   -- nuevo | convertido | rechazado
  cliente_id       bigint,                          -- si compró con su acceso de cliente
  nombre           text not null,
  nit              text,
  telefono         text,
  email            text,
  direccion        text,
  notas            text,
  forma_pago       text,                            -- transferencia | contra_entrega | credito
  items            jsonb not null,                  -- [{codigo,nombre,unidad,precio,cantidad}]
  total            numeric(12,2) not null,
  empresa_asignada text,                            -- la que se eligió al convertir
  pedidos_ids      jsonb,                           -- ids de los PED creados
  atendido_por     text,
  atendido_el      timestamptz,
  motivo_rechazo   text,
