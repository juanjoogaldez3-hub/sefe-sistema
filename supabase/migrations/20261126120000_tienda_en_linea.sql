-- ── 4) Configuración de la tienda (nace apagada) ─────────────
insert into public.ajustes (clave, valor)
values ('tienda', '{"activa":false,"mostrarAgotados":false,"whatsapp":"","pedidoMinimo":0,"aviso":""}'::jsonb)
on conflict (clave) do nothing;

create or replace function public.tienda__config()
returns jsonb
language sql stable security definer
set search_path = public, pg_temp
as $$
  select '{"activa":false,"mostrarAgotados":false,"whatsapp":"","pedidoMinimo":0,"aviso":""}'::jsonb
         || coalesce((
              select case when jsonb_typeof(a.valor) = 'string' then (a.valor #>> '{}')::jsonb else a.valor end
                from ajustes a where a.clave = 'tienda'), '{}'::jsonb)
$$;

-- Cliente dueño de un token de sesión (null si no hay o venció).
create or replace function public.tienda__cliente_de(p_token text)
returns bigint
language sql stable security definer
set search_path = public, pg_temp
as $$
  select s.cliente_id
    from tienda_sesiones s
    join clientes c on c.id = s.cliente_id and c.activo
   where p_token is not null and length(p_token) >= 32
     and s.token_hash = encode(sha256(convert_to(p_token, 'UTF8')), 'hex')
     and s.vence > now()
$$;

-- ── 5) Catálogo unificado (una ficha por código) ─────────────
-- `tope` = lo más que se puede pedir de ese código (lo que hay en la
-- empresa que más tiene). No sale del servidor tal cual: el catálogo
-- sólo dice si hay o no, y hasta cuánto deja pedir.
create or replace function public.tienda__productos(p_cliente_id bigint)
returns table (codigo text, nombre text, marca text, categoria text, unidad text,
               imagen text, descripcion text, precio numeric, tope numeric)
language sql stable security definer
set search_path = public, pg_temp
as $$
  with cli as (
    select c.empresa, coalesce(c.precios, '{}'::jsonb) as precios
      from clientes c where c.id = p_cliente_id and c.activo
  ),
  base as (
    select upper(trim(p.codigo)) as cod, p.id, p.nombre, p.marca, p.categoria, p.unidad,
           p.imagen_url, p.tienda_descripcion, p.precio as lista, p.empresa,
           greatest(case when p.tipo_empaque = 'caja_unidad' then coalesce(p.stock_cajas, 0)
                         else coalesce(p.stock, 0) end, 0) as disp,
           coalesce(p.empresa = (select empresa from cli), false) as es_mia,
           (select case when jsonb_typeof(cli.precios -> (p.id::text)) = 'number'
                        then (cli.precios ->> (p.id::text))::numeric end
              from cli) as especial
      from productos p
     where p.activo
       and not coalesce(p.tienda_oculto, false)
       and coalesce(p.precio, 0) > 0
       and coalesce(trim(p.codigo), '') <> ''
       and lower(coalesce(p.categoria, '')) <> 'servicios'
  ),
  agg as (
    select cod,
           max(disp) as tope,
           max(lista) as precio_max,
           max(lista) filter (where es_mia) as precio_mia,
           max(especial) filter (where es_mia and especial > 0) as precio_esp,
           max(imagen_url) as imagen,
           max(nullif(trim(categoria), '')) as categoria,
           max(nullif(trim(marca), '')) as marca,
           max(nullif(trim(tienda_descripcion), '')) as descripcion
      from base group by cod
  ),
  ficha as (
    select distinct on (cod) cod, nombre, unidad
      from base order by cod, (empresa <> 'SEFE'), id
  )
  select a.cod, f.nombre, a.marca, a.categoria, f.unidad, a.imagen, a.descripcion,
         round(coalesce(a.precio_esp, a.precio_mia, a.precio_max), 2), a.tope
    from agg a join ficha f using (cod)
$$;

-- Lo que baja la página de la tienda.
create or replace function public.tienda_catalogo(p_token text default null)
returns jsonb
language plpgsql stable security definer
set search_path = public, pg_temp
as $$
declare
  v_cfg   jsonb := tienda__config();
  v_previa boolean := coalesce(sefe_activo(), false);  -- personal del sistema: vista previa
  v_cli   bigint;
  v_cliente jsonb;
  v_prods jsonb;
begin
  if not coalesce((v_cfg->>'activa')::boolean, false) and not v_previa then
    return jsonb_build_object('ok', true, 'activa', false);
  end if;

  v_cli := tienda__cliente_de(p_token);
  if v_cli is not null then
    select jsonb_build_object('nombre', c.nombre, 'nit', c.nit,
                              'direccion', coalesce(nullif(c.direccion_entrega, ''), c.direccion),
                              'email', c.email, 'credito', coalesce(c.tiempo_credito, 0))
      into v_cliente from clientes c where c.id = v_cli;
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
           'c', t.codigo, 'n', t.nombre, 'm', t.marca, 'g', t.categoria, 'u', t.unidad,
           'i', t.imagen, 'd', t.descripcion, 'p', t.precio,
           'x', least(t.tope, 500)) order by t.nombre), '[]'::jsonb)
    into v_prods
    from tienda__productos(v_cli) t
   where t.tope > 0 or coalesce((v_cfg->>'mostrarAgotados')::boolean, false);

  return jsonb_build_object(
    'ok', true, 'activa', true,
    'previa', not coalesce((v_cfg->>'activa')::boolean, false),
    'whatsapp', coalesce(v_cfg->>'whatsapp', ''),
    'pedidoMinimo', coalesce((v_cfg->>'pedidoMinimo')::numeric, 0),
    'aviso', coalesce(v_cfg->>'aviso', ''),
    'cliente', v_cliente,
    'productos', v_prods);
end $$;

-- ── 6) Entrar / salir como cliente ───────────────────────────
-- Devuelve {ok:false,error} en vez de lanzar error, para que el conteo
-- de intentos fallidos SÍ quede guardado.
create or replace function public.tienda_entrar(p_nit text, p_clave text)
returns jsonb
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
  v_nit   text := upper(regexp_replace(coalesce(p_nit, ''), '[^0-9A-Za-z]', '', 'g'));
  v_cli   bigint;
  v_nombre text;
  v_token text;
begin
  if not coalesce((tienda__config()->>'activa')::boolean, false) and not coalesce(sefe_activo(), false) then
    return jsonb_build_object('ok', false, 'error', 'La tienda no está disponible.');
  end if;
  if length(v_nit) < 3 or length(coalesce(p_clave, '')) < 4 or length(p_clave) > 72 then
    return jsonb_build_object('ok', false, 'error', 'NIT o clave incorrectos.');
  end if;

  if exists (select 1 from tienda_accesos a join clientes c on c.id = a.cliente_id
              where upper(regexp_replace(coalesce(c.nit, ''), '[^0-9A-Za-z]', '', 'g')) = v_nit
                and a.bloqueado_hasta > now()) then
    return jsonb_build_object('ok', false, 'error', 'Demasiados intentos. Probá de nuevo en 15 minutos.');
  end if;

  select c.id, c.nombre into v_cli, v_nombre
    from tienda_accesos a join clientes c on c.id = a.cliente_id and c.activo
   where upper(regexp_replace(coalesce(c.nit, ''), '[^0-9A-Za-z]', '', 'g')) = v_nit
     and a.clave_hash = extensions.crypt(p_clave, a.clave_hash)
   order by c.id limit 1;

  if v_cli is null then
    update tienda_accesos a
       set intentos = a.intentos + 1,
           bloqueado_hasta = case when a.intentos + 1 >= 8 then now() + interval '15 minutes' else a.bloqueado_hasta end
      from clientes c
     where c.id = a.cliente_id
       and upper(regexp_replace(coalesce(c.nit, ''), '[^0-9A-Za-z]', '', 'g')) = v_nit;
    return jsonb_build_object('ok', false, 'error', 'NIT o clave incorrectos.');
  end if;

  update tienda_accesos set intentos = 0, bloqueado_hasta = null where cliente_id = v_cli;
  delete from tienda_sesiones where vence < now();
  v_token := replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', '');
  insert into tienda_sesiones (token_hash, cliente_id, vence)
  values (encode(sha256(convert_to(v_token, 'UTF8')), 'hex'), v_cli, now() + interval '30 days');
  return jsonb_build_object('ok', true, 'token', v_token, 'nombre', v_nombre);
end $$;

create or replace function public.tienda_salir(p_token text)
returns jsonb
language sql security definer
set search_path = public, pg_temp
as $$
  with b as (delete from tienda_sesiones
              where token_hash = encode(sha256(convert_to(coalesce(p_token, ''), 'UTF8')), 'hex')
              returning 1)
  select jsonb_build_object('ok', true)
$$;

-- ── 7) Crear el pedido web ───────────────────────────────────
-- Los precios y el total se calculan acá; del navegador sólo se toman
-- códigos y cantidades.
create or replace function public.tienda_crear_pedido(p_pedido jsonb, p_token text default null)
returns jsonb
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
  v_cfg   jsonb := tienda__config();
  v_ip    text;
  v_cli   bigint;
  v_c     record;
  v_nombre text; v_nit text; v_tel text; v_email text; v_dir text; v_notas text; v_pago text;
  v_items jsonb; v_total numeric; v_n integer; v_malo text; v_id bigint;
begin
  if not coalesce((v_cfg->>'activa')::boolean, false) then
    return jsonb_build_object('ok', false, 'error', 'La tienda no está recibiendo pedidos en este momento.');
  end if;
  if p_pedido is null or jsonb_typeof(p_pedido) <> 'object'
     or jsonb_typeof(p_pedido->'items') is distinct from 'array' then
    return jsonb_build_object('ok', false, 'error', 'Pedido inválido.');
  end if;

  begin
    v_ip := nullif(trim(split_part(coalesce(current_setting('request.headers', true)::json->>'x-forwarded-for', ''), ',', 1)), '');
  exception when others then v_ip := null; end;
  if v_ip is not null and (select count(*) from pedidos_web where ip = v_ip and creado > now() - interval '1 hour') >= 6 then
    return jsonb_build_object('ok', false, 'error', 'Ya enviaste varios pedidos hace poco. Esperá un rato o escribinos.');
  end if;
  if (select count(*) from pedidos_web where creado > now() - interval '1 day') >= 400 then
    return jsonb_build_object('ok', false, 'error', 'No podemos recibir más pedidos por hoy. Escribinos, por favor.');
  end if;

  -- v_c arranca vacío (comprador sin acceso de cliente).
  select null::text as nombre, null::text as nit, null::text as email, null::text as dir, 0 as credito into v_c;
  v_cli := tienda__cliente_de(p_token);
  if v_cli is not null then
    select c.nombre, c.nit, c.email, coalesce(nullif(c.direccion_entrega, ''), c.direccion) as dir,
           coalesce(c.tiempo_credito, 0) as credito
      into v_c from clientes c where c.id = v_cli;
  end if;

  v_nombre := left(trim(coalesce(nullif(trim(p_pedido->>'nombre'), ''), v_c.nombre, '')), 120);
  v_nit    := left(upper(trim(coalesce(nullif(trim(p_pedido->>'nit'), ''), v_c.nit, 'CF'))), 20);
  v_tel    := left(regexp_replace(coalesce(p_pedido->>'telefono', ''), '[^0-9+]', '', 'g'), 16);
  v_email  := left(trim(coalesce(nullif(trim(p_pedido->>'email'), ''), v_c.email, '')), 120);
  v_dir    := left(trim(coalesce(nullif(trim(p_pedido->>'direccion'), ''), v_c.dir, '')), 300);
  v_notas  := left(trim(coalesce(p_pedido->>'notas', '')), 500);
  v_pago   := coalesce(p_pedido->>'formaPago', '');

  if length(v_nombre) < 2 then return jsonb_build_object('ok', false, 'error', 'Escribí tu nombre.'); end if;
  if length(regexp_replace(v_tel, '[^0-9]', '', 'g')) < 8 then return jsonb_build_object('ok', false, 'error', 'Escribí un teléfono válido (8 dígitos).'); end if;
  if length(v_dir) < 5 then return jsonb_build_object('ok', false, 'error', 'Escribí la dirección de entrega.'); end if;
  if v_pago not in ('transferencia', 'contra_entrega', 'credito') then
    return jsonb_build_object('ok', false, 'error', 'Elegí la forma de pago.');
  end if;
  if v_pago = 'credito' and coalesce(v_c.credito, 0) <= 0 then
    return jsonb_build_object('ok', false, 'error', 'El pago a crédito es sólo para clientes con crédito autorizado.');
  end if;

  v_n := jsonb_array_length(p_pedido->'items');
  if v_n < 1 or v_n > 80 then
    return jsonb_build_object('ok', false, 'error', 'El carrito está vacío o tiene demasiados productos.');
  end if;

  -- Cantidades: enteras y positivas.
  if exists (select 1 from jsonb_array_elements(p_pedido->'items') it
              where coalesce(it->>'c', '') = ''
                 or coalesce(it->>'q', '') !~ '^[0-9]{1,4}$'
                 or (it->>'q')::int < 1) then
    return jsonb_build_object('ok', false, 'error', 'Hay una cantidad inválida en el carrito.');
  end if;

  with pedido as (
    select upper(trim(it->>'c')) as cod, sum((it->>'q')::int) as cant
      from jsonb_array_elements(p_pedido->'items') it group by 1
  ),
  cruce as (
    select pe.cod, pe.cant, t.nombre, t.unidad, t.precio, t.tope
      from pedido pe left join tienda__productos(v_cli) t on t.codigo = pe.cod
  )
  select
    (select coalesce(c.nombre, c.cod) ||
            case when c.nombre is null then ' ya no está disponible'
                 when c.tope <= 0 then ' está agotado'
                 else ' (quedan ' || trunc(c.tope) || ')' end
       from cruce c where c.nombre is null or c.cant > c.tope limit 1),
    (select jsonb_agg(jsonb_build_object('codigo', c.cod, 'nombre', c.nombre, 'unidad', c.unidad,
                                         'precio', c.precio, 'cantidad', c.cant) order by c.nombre)
       from cruce c),
    (select round(sum(c.precio * c.cant), 2) from cruce c)
    into v_malo, v_items, v_total;

  if v_malo is not null then
    return jsonb_build_object('ok', false, 'error', 'No se pudo enviar: ' || v_malo || '. Ajustá el carrito y probá de nuevo.');
  end if;
  if v_total < coalesce((v_cfg->>'pedidoMinimo')::numeric, 0) then
    return jsonb_build_object('ok', false, 'error', 'El pedido mínimo es de Q' || (v_cfg->>'pedidoMinimo') || '.');
  end if;

  insert into pedidos_web (cliente_id, nombre, nit, telefono, email, direccion, notas, forma_pago, items, total, ip)
  values (v_cli, v_nombre, v_nit, v_tel, nullif(v_email, ''), v_dir, nullif(v_notas, ''), v_pago, v_items, v_total, v_ip)
  returning id into v_id;

  return jsonb_build_object('ok', true, 'numero', 'WEB-' || lpad(v_id::text, 4, '0'), 'total', v_total,
                            'whatsapp', coalesce(v_cfg->>'whatsapp', ''));
end $$;

-- ── 8) Personal: dar / quitar el acceso de un cliente ────────
create or replace function public.tienda_poner_clave(p_cliente_id bigint, p_clave text)
returns jsonb
language plpgsql security definer
set search_path = public, pg_temp
as $$
begin
  if not coalesce(sefe_puede_escribir(), false) then
    return jsonb_build_object('ok', false, 'error', 'Sin permiso.');
  end if;
  if length(coalesce(p_clave, '')) < 6 or length(p_clave) > 72 then
    return jsonb_build_object('ok', false, 'error', 'La clave debe tener al menos 6 caracteres.');
  end if;
  if not exists (select 1 from clientes where id = p_cliente_id) then
    return jsonb_build_object('ok', false, 'error', 'Cliente no encontrado.');
  end if;
  insert into tienda_accesos (cliente_id, clave_hash, creado_por)
  values (p_cliente_id, extensions.crypt(p_clave, extensions.gen_salt('bf', 10)), auth.jwt()->>'email')
  on conflict (cliente_id) do update
    set clave_hash = excluded.clave_hash, intentos = 0, bloqueado_hasta = null,
        creado = now(), creado_por = excluded.creado_por;
  delete from tienda_sesiones where cliente_id = p_cliente_id;
  return jsonb_build_object('ok', true);
end $$;

create or replace function public.tienda_quitar_clave(p_cliente_id bigint)
returns jsonb
language plpgsql security definer
set search_path = public, pg_temp
as $$
begin
  if not coalesce(sefe_puede_escribir(), false) then
    return jsonb_build_object('ok', false, 'error', 'Sin permiso.');
  end if;
  delete from tienda_accesos where cliente_id = p_cliente_id;
  delete from tienda_sesiones where cliente_id = p_cliente_id;
  return jsonb_build_object('ok', true);
end $$;

